let activeCollectionIndex = 0;
let activeSessionIndex = 0;
let activePhotoIndex = 0;

initCoreXformerFeedbackLibrary();

function initCoreXformerFeedbackLibrary() {
  const shell = document.querySelector("[data-feedback-summary]");

  if (!shell || !FEEDBACK_COLLECTIONS.length) {
    return;
  }

  bindFeedbackControls();
  renderFeedbackCollection();
}

function bindFeedbackControls() {
  document.querySelector("[data-feedback-collection-prev]")?.addEventListener("click", () => moveCollection(-1));
  document.querySelector("[data-feedback-collection-next]")?.addEventListener("click", () => moveCollection(1));
  document.querySelector("[data-feedback-session-prev]")?.addEventListener("click", () => moveSession(-1));
  document.querySelector("[data-feedback-session-next]")?.addEventListener("click", () => moveSession(1));
  document.querySelector("[data-feedback-photo-prev]")?.addEventListener("click", () => movePhoto(-1));
  document.querySelector("[data-feedback-photo-next]")?.addEventListener("click", () => movePhoto(1));

  bindSwipeSurface("[data-feedback-collection-swipe]", moveCollection);
  bindSwipeSurface("[data-feedback-session-swipe]", moveSession);
  bindSwipeSurface(".feedback-photo-stage", movePhoto);
  bindArrowKeys("[data-feedback-collection-swipe]", moveCollection);
  bindArrowKeys("[data-feedback-session-swipe]", moveSession);
  bindArrowKeys(".feedback-photo-stage", movePhoto);
}

function bindSwipeSurface(selector, move) {
  const surface = document.querySelector(selector);

  if (!surface) {
    return;
  }

  let startX = null;

  surface.addEventListener("pointerdown", (event) => {
    if (event.pointerType !== "mouse") {
      startX = event.clientX;
    }
  });

  surface.addEventListener("pointercancel", () => {
    startX = null;
  });

  surface.addEventListener("pointerup", (event) => {
    if (startX === null || event.pointerType === "mouse") {
      return;
    }

    const distance = event.clientX - startX;
    startX = null;

    if (Math.abs(distance) >= 44) {
      move(distance > 0 ? -1 : 1);
    }
  });
}

function bindArrowKeys(selector, move) {
  document.querySelector(selector)?.addEventListener("keydown", (event) => {
    if (event.key === "ArrowLeft") {
      event.preventDefault();
      move(-1);
    }

    if (event.key === "ArrowRight") {
      event.preventDefault();
      move(1);
    }
  });
}

function moveCollection(direction) {
  if (FEEDBACK_COLLECTIONS.length < 2) {
    return;
  }

  activeCollectionIndex = wrapIndex(activeCollectionIndex + direction, FEEDBACK_COLLECTIONS.length);
  activeSessionIndex = 0;
  activePhotoIndex = 0;
  renderFeedbackCollection();
}

function moveSession(direction) {
  const sessions = currentCollection()?.sessions || [];

  if (sessions.length < 2) {
    return;
  }

  activeSessionIndex = wrapIndex(activeSessionIndex + direction, sessions.length);
  activePhotoIndex = 0;
  renderSession(currentCollection());
}

function movePhoto(direction) {
  const photos = currentSession()?.photos || [];

  if (photos.length < 2) {
    return;
  }

  activePhotoIndex = wrapIndex(activePhotoIndex + direction, photos.length);
  renderPhotoGallery(photos);
}

function renderFeedbackCollection() {
  const collection = currentCollection();

  if (!collection) {
    return;
  }

  const hasMultipleCollections = FEEDBACK_COLLECTIONS.length > 1;
  setControlState("[data-feedback-collection-prev]", !hasMultipleCollections);
  setControlState("[data-feedback-collection-next]", !hasMultipleCollections);
  setElementText("[data-feedback-collection-progress]", `${activeCollectionIndex + 1} of ${FEEDBACK_COLLECTIONS.length}`);
  setElementText("[data-feedback-cohort-kicker]", collection.kicker);
  setElementText("[data-feedback-cohort-title]", collection.title);
  setElementText("[data-feedback-cohort-description]", collection.description);
  setElementText("[data-feedback-cohort-dates]", collection.dates);
  setElementText("[data-feedback-cohort-forms]", collection.formsLabel);

  renderSessionTabs(collection.sessions || []);
  renderSession(collection);
}

function renderSession(collection) {
  const sessions = collection.sessions || [];
  const sessionCard = document.querySelector("[data-feedback-session-card]");
  const empty = document.querySelector("[data-feedback-session-empty]");
  const hasSessions = sessions.length > 0;

  setElementHidden(sessionCard, !hasSessions);
  setElementHidden(empty, hasSessions);
  setControlState("[data-feedback-session-prev]", sessions.length < 2);
  setControlState("[data-feedback-session-next]", sessions.length < 2);

  if (!hasSessions) {
    setElementText("[data-feedback-session-progress]", "No statistics yet");
    setElementText("[data-feedback-session-empty-copy]", collection.emptyCopy || "Completed session feedback has not yet been added.");
    setElementText("[data-feedback-learning-eyebrow]", `${collection.title} | participant learning`);
    setElementText("[data-feedback-learning-heading]", "What participants carried from this session.");
    setElementText("[data-feedback-context]", collection.emptyCopy || "Participant takeaways will appear here when the source material is available.");
    renderSessionStats([]);
    renderLearningTakeaways([]);
    renderPhotoGallery([]);
    return;
  }

  activeSessionIndex = wrapIndex(activeSessionIndex, sessions.length);
  const session = sessions[activeSessionIndex];

  setElementText("[data-feedback-session-progress]", `${session.label} of ${sessions.length}`);
  setElementText("[data-feedback-session-kicker]", collection.title);
  setElementText("[data-feedback-session-title]", `${session.label} | ${session.date}`);
  setElementText("[data-feedback-session-context]", session.context);
  setElementText("[data-feedback-learning-eyebrow]", `${session.label} | participant learning`);
  setElementText("[data-feedback-learning-heading]", "What participants carried from this session.");
  setElementText("[data-feedback-context]", session.context);
  setLink("[data-feedback-session-report]", session.report);

  renderSessionTabs(sessions);
  renderSessionStats(session.stats || []);
  renderLearningTakeaways(session.takeaways || []);
  renderPhotoGallery(session.photos || []);
}

function renderSessionTabs(sessions) {
  const tabs = document.querySelector("[data-feedback-session-tabs]");

  if (!tabs) {
    return;
  }

  tabs.replaceChildren();

  if (!sessions.length) {
    const placeholder = document.createElement("span");
    placeholder.className = "feedback-session-tab feedback-session-tab-empty";
    placeholder.textContent = "Session details pending";
    tabs.appendChild(placeholder);
    return;
  }

  sessions.forEach((session, index) => {
    const button = document.createElement("button");
    const label = document.createElement("strong");
    const date = document.createElement("span");

    button.type = "button";
    button.className = "feedback-session-tab";
    button.setAttribute("role", "tab");
    button.setAttribute("aria-selected", String(index === activeSessionIndex));
    button.addEventListener("click", () => {
      activeSessionIndex = index;
      activePhotoIndex = 0;
      renderSession(currentCollection());
    });

    label.textContent = session.label;
    date.textContent = session.date;
    button.append(label, date);
    tabs.appendChild(button);
  });

  tabs.querySelector('[aria-selected="true"]')?.scrollIntoView({ behavior: "smooth", block: "nearest", inline: "center" });
}

function renderSessionStats(stats) {
  const grid = document.querySelector("[data-feedback-session-stats]");

  if (!grid) {
    return;
  }

  grid.replaceChildren();

  stats.forEach((stat, index) => {
    const article = document.createElement("article");
    const label = document.createElement("span");
    const value = document.createElement("strong");
    const note = document.createElement("p");

    article.className = `feedback-session-stat${index === stats.length - 1 ? " feedback-session-stat-accent" : ""}`;
    label.textContent = stat.label;
    value.textContent = stat.value;
    note.textContent = stat.note;
    article.append(label, value, note);
    grid.appendChild(article);
  });
}

function renderLearningTakeaways(takeaways) {
  const grid = document.querySelector("[data-feedback-library-grid]");

  if (!grid) {
    return;
  }

  grid.replaceChildren();
  setElementText(
    "[data-feedback-learning-count]",
    takeaways.length ? `${takeaways.length} anonymised form responses` : "No responses available"
  );

  if (!takeaways.length) {
    const emptyCard = document.createElement("article");
    const copy = document.createElement("p");
    emptyCard.className = "feedback-learning-card feedback-learning-card-empty";
    copy.textContent = "Participant takeaways have not yet been added for this session.";
    emptyCard.appendChild(copy);
    grid.appendChild(emptyCard);
    return;
  }

  takeaways.forEach((takeaway, index) => {
    const article = document.createElement("article");
    const copy = document.createElement("p");
    const source = document.createElement("span");

    article.className = "feedback-learning-card";
    copy.textContent = takeaway;
    source.textContent = `Anonymised response ${String(index + 1).padStart(2, "0")} of ${takeaways.length}`;
    article.append(copy, source);
    grid.appendChild(article);
  });
}

function renderPhotoGallery(photos) {
  const viewer = document.querySelector(".feedback-photo-viewer");
  const progress = document.querySelector("[data-feedback-photo-progress]");
  const empty = document.querySelector("[data-feedback-photo-empty]");
  const thumbnails = document.querySelector("[data-feedback-photo-thumbnails]");
  const hasPhotos = photos.length > 0;

  setElementHidden(viewer, !hasPhotos);
  setElementHidden(progress, !hasPhotos);
  setElementHidden(thumbnails, !hasPhotos);
  setElementHidden(empty, hasPhotos);

  if (!hasPhotos) {
    thumbnails?.replaceChildren();
    return;
  }

  activePhotoIndex = wrapIndex(activePhotoIndex, photos.length);
  const photo = photos[activePhotoIndex];
  const hasMultiplePhotos = photos.length > 1;

  setControlState("[data-feedback-photo-prev]", !hasMultiplePhotos);
  setControlState("[data-feedback-photo-next]", !hasMultiplePhotos);
  setImage("[data-feedback-photo-image]", photo.src, photo.alt);
  setElementText("[data-feedback-photo-label]", photo.label);
  setElementText("[data-feedback-photo-caption]", photo.caption);
  setElementText("[data-feedback-photo-progress]", `${activePhotoIndex + 1} of ${photos.length}`);
  renderPhotoThumbnails(photos);
}

function renderPhotoThumbnails(photos) {
  const list = document.querySelector("[data-feedback-photo-thumbnails]");

  if (!list) {
    return;
  }

  list.replaceChildren();

  photos.forEach((photo, index) => {
    const button = document.createElement("button");
    const image = document.createElement("img");
    const label = document.createElement("span");

    button.className = "feedback-photo-thumbnail";
    button.type = "button";
    button.setAttribute("aria-label", `Show ${photo.label}`);
    button.setAttribute("aria-current", index === activePhotoIndex ? "true" : "false");
    button.addEventListener("click", () => {
      activePhotoIndex = index;
      renderPhotoGallery(currentSession()?.photos || []);
    });

    image.src = photo.src;
    image.alt = "";
    image.loading = "lazy";
    image.decoding = "async";
    label.textContent = photo.label.split("|")[0].trim();
    button.append(image, label);
    list.appendChild(button);
  });
}

function currentCollection() {
  return FEEDBACK_COLLECTIONS[activeCollectionIndex];
}

function currentSession() {
  return currentCollection()?.sessions?.[activeSessionIndex];
}

function setElementText(selector, value) {
  const element = document.querySelector(selector);

  if (element) {
    element.textContent = value;
  }
}

function setElementHidden(element, hidden) {
  if (element) {
    element.hidden = hidden;
  }
}

function setImage(selector, src, alt) {
  const image = document.querySelector(selector);

  if (image) {
    image.src = src;
    image.alt = alt;
  }
}

function setLink(selector, href) {
  const link = document.querySelector(selector);

  if (!link) {
    return;
  }

  link.hidden = !href;

  if (href) {
    link.href = href;
  }
}

function setControlState(selector, disabled) {
  const control = document.querySelector(selector);

  if (control instanceof HTMLButtonElement) {
    control.disabled = disabled;
    control.setAttribute("aria-disabled", String(disabled));
  }
}

function wrapIndex(index, length) {
  return length ? (index + length) % length : 0;
}
