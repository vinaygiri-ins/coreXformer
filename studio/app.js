async function saveCurrentSection(nextStatus) {
  if (!canEdit()) {
    showMessage(dom.editorMessage, "Only owner or editor accounts can save content changes.", "error");
    return;
  }

  if (nextStatus === "published" && !canPublish()) {
    showMessage(dom.editorMessage, "This account can save drafts, but it is not allowed to publish updates yet.", "error");
    return;
  }

  const currentSection = getCurrentSection();

  if (!currentSection?.id) {
    showMessage(dom.editorMessage, "Choose a real section before saving.", "error");
    return;
  }

  const payload = {
    eyebrow: dom.fieldEyebrow.value.trim(),
    heading: dom.fieldHeading.value.trim(),
    summary: dom.fieldSummary.value.trim(),
    body: dom.fieldBody.value.trim(),
    status: nextStatus,
    updated_by: state.session.user.id
  };

  if (nextStatus === "published") {
    payload.published_at = new Date().toISOString();
  }

  setBusy("save", true);
  showMessage(dom.editorMessage, nextStatus === "published" ? "Publishing section update..." : "Saving draft...");

  const { data, error } = await state.supabase
    .from("page_sections")
    .update(payload)
    .eq("id", currentSection.id)
    .select("id, page_id, slug, label, section_type, eyebrow, heading, summary, body, status, sort_order, visible, published_at")
    .single();

  setBusy("save", false);

  if (error) {
    showMessage(dom.editorMessage, error.message, "error");
    renderStudio();
    return;
  }

  replaceSectionInState(data);
  showMessage(dom.editorMessage, nextStatus === "published" ? "Section published successfully." : "Draft saved successfully.");
  renderStudio();
}

function replaceSectionInState(sectionRow) {
  const page = state.pages.find((entry) => entry.id === sectionRow.page_id);

  if (!page) {
    return;
  }

  const sectionIndex = page.sections.findIndex((section) => section.id === sectionRow.id);
  const normalizedSection = {
    id: sectionRow.id,
    pageId: sectionRow.page_id,
    slug: sectionRow.slug,
    label: sectionRow.label,
    type: sectionRow.section_type,
    eyebrow: sectionRow.eyebrow || "",
    heading: sectionRow.heading || "",
    summary: sectionRow.summary || "",
    body: sectionRow.body || "",
    status: sectionRow.status,
    sortOrder: sectionRow.sort_order,
    visible: sectionRow.visible,
    publishedAt: sectionRow.published_at
  };

  if (sectionIndex === -1) {
    page.sections.push(normalizedSection);
    page.sections.sort((left, right) => left.sortOrder - right.sortOrder);
    return;
  }

  page.sections[sectionIndex] = normalizedSection;
}

