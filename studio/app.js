async function handleSession(session) {
  state.session = session ?? null;
  state.profile = null;

  if (!state.session) {
    state.pages = [];
    state.currentPageIndex = 0;
    state.currentSectionIndex = 0;
    state.inquiryCounts = zeroInquiryCounts();
    state.productOps.facilitators = [];
    state.productOps.selectedFacilitatorId = "";
    state.productOps.creatingFacilitator = false;
    state.productOps.facilitatorProfile = null;
    state.productOps.productLink = null;
    state.productOps.sessionRun = null;
    state.productOps.sessionAssignment = null;
    state.productOps.publicFacilitatorRow = null;
    state.productOps.note = null;
    state.productOps.feedbackRows = [];
    resetCollaborationState();
    clearMessage(dom.editorMessage);
    clearMessage(dom.authMessage);
    clearMessage(dom.productOpsMessage);
    clearMessage(dom.collaborationMessage);
    setAuthState("Signed out. Redirecting you to private studio access...");
    renderStudio();
    window.location.replace(buildAdminAccessPath());
    return;
  }

  setAuthState(`Signed in as ${state.session.user.email}. Loading your profile and content...`);

  try {
    state.profile = await waitForProfile(state.session.user.id);

    if (!state.profile) {
      showMessage(dom.authMessage, "Your account exists, but the studio profile has not been created yet. Wait a moment and sign in again.", "error");
      setAuthState("Signed in, but the admin profile is not ready yet.");
      state.pages = [];
      renderStudio();
      return;
    }

    if (!canEdit()) {
      setAuthState("This account belongs to the facilitator side. Redirecting to the facilitator workspace...");
      window.location.replace(window.COREXFORMER_STUDIO_CONFIG?.facilitatorWorkspacePath || "/studio/facilitator");
      return;
    }

    await Promise.all([loadPages(), loadInquiryCounts(), loadProgramOpsData()]);
    clearMessage(dom.authMessage);
    setAuthState(buildAuthSummary());
  } catch (error) {
    showMessage(dom.authMessage, error.message || "The studio could not load data from Supabase.", "error");
    setAuthState("Signed in, but the content dashboard could not be loaded.");
  }

  renderStudio();
}

async function waitForProfile(userId, attempts = 6) {
  for (let attempt = 0; attempt < attempts; attempt += 1) {
    const { data, error } = await state.supabase
      .from("profiles")
      .select("id, email, full_name, role, can_publish")
      .eq("id", userId)
      .maybeSingle();

    if (error) {
      throw error;
    }

    if (data) {
      return data;
    }

    await sleep(900);
  }

  return null;
}

async function signIn() {
  const email = dom.emailInput.value.trim();
  const password = dom.passwordInput.value;

  if (!email || !password) {
    showMessage(dom.authMessage, "Enter both email and password to sign in.", "error");
    return;
  }

  setBusy("auth", true);
  showMessage(dom.authMessage, "Signing you into CoreXformer Studio...");

  const { error } = await state.supabase.auth.signInWithPassword({ email, password });

  setBusy("auth", false);

  if (error) {
    showMessage(dom.authMessage, error.message, "error");
    return;
  }

  showMessage(dom.authMessage, "Signed in. Loading your workspace...");
}

async function signUp() {
  const email = dom.emailInput.value.trim();
  const password = dom.passwordInput.value;
  const fullName = dom.fullNameInput.value.trim();

  if (!email || !password) {
    showMessage(dom.authMessage, "Enter an email and password before creating the first owner account.", "error");
    return;
  }

  setBusy("auth", true);
  showMessage(dom.authMessage, "Creating the CoreXformer studio account...");

  const { data, error } = await state.supabase.auth.signUp({
    email,
    password,
    options: {
      data: {
        full_name: fullName
      }
    }
  });

  setBusy("auth", false);

  if (error) {
    showMessage(dom.authMessage, error.message, "error");
    return;
  }

  if (data.session) {
    showMessage(dom.authMessage, "Account created. This session should now become the first owner if it is the first user in the project.");
    return;
  }

  showMessage(dom.authMessage, "Account created. If email confirmation is enabled for this project, confirm the email first and then sign in.");
}

